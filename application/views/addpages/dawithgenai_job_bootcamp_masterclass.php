        function handleFormSubmit(e) {
            e.preventDefault();

            console.log('=== FORM SUBMIT TRIGGERED ===');
            console.log('Form ID:', e.target.id);

            const form = e.target;
            const submitBtn = form.querySelector('button[type="submit"]');

            console.log('Submit button found:', !!submitBtn);

            // Get form values - handle popup form differently
            let firstname, mobile, email;

            if (form.id === 'popupForm') {
                console.log('Processing popup form...');
                // Popup form has different element IDs
                const firstnameInput = document.getElementById('popup-first-name');
                const mobileInput = document.getElementById('popup-mobile');
                const emailInput = document.getElementById('popup-email');

                console.log('Input elements found:', {
                    firstname: !!firstnameInput,
                    mobile: !!mobileInput,
                    email: !!emailInput
                });

                firstname = firstnameInput ? firstnameInput.value.trim() : '';
                mobile = mobileInput ? mobileInput.value.trim() : '';
                email = emailInput ? emailInput.value.trim() : '';
            } else {
                // Hero and sticky forms use FormData
                const formData = new FormData(form);
                firstname = formData.get('firstname') ? formData.get('firstname').trim() : '';
                mobile = formData.get('mobile') ? formData.get('mobile').trim() : '';
                email = formData.get('email') ? formData.get('email').trim() : '';
            }

            console.log('Form values:', {
                firstname,
                mobile,
                email
            });

            // Validate
            if (!firstname || !mobile || !email) {
                alert("Please fill all required fields");
                return false;
            }

            if (!/^[0-9]{10}$/.test(mobile)) {
                alert("Please enter a valid 10 digit mobile number");
                return false;
            }

            if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
                alert("Please enter a valid email address");
                return false;
            }

            console.log('Validation passed! Creating form data...');

            // Create FormData with validated values
            const submitData = new FormData();
