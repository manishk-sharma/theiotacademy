<script>
document.addEventListener("DOMContentLoaded", function () {

    const MASTERCLASS_PAGE_SLUG = "data-analytics-gen-ai-masterclass";

    const API_URL =
        window.location.origin +
        "/api/masterclass/date?page_slug=" +
        encodeURIComponent(MASTERCLASS_PAGE_SLUG);

    const dateEl = document.getElementById("thankyouMasterclassDate");
    const timeEl = document.getElementById("thankyouMasterclassTime");
    const whatsappBtn = document.getElementById("waJoinBtn");

    const daysEl = document.getElementById("cd-d");
    const hoursEl = document.getElementById("cd-h");
    const minutesEl = document.getElementById("cd-m");
    const secondsEl = document.getElementById("cd-s");

    let targetDate = null;

    function pad(value) {
        return String(value).padStart(2, "0");
    }

    function updateCountdown() {

    if (!targetDate || Number.isNaN(targetDate.getTime())) {
        return;
    }

    let totalSeconds = Math.floor(
        (targetDate.getTime() - Date.now()) / 1000
    );

    if (totalSeconds < 0) {
        totalSeconds = 0;
    }

    const days = Math.floor(totalSeconds / 86400);
    const hours = Math.floor((totalSeconds % 86400) / 3600);
    const minutes = Math.floor((totalSeconds % 3600) / 60);
    const seconds = totalSeconds % 60;

    if (daysEl) daysEl.textContent = String(days).padStart(2, "0");
    if (hoursEl) hoursEl.textContent = String(hours).padStart(2, "0");
    if (minutesEl) minutesEl.textContent = String(minutes).padStart(2, "0");
    if (secondsEl) secondsEl.textContent = String(seconds).padStart(2, "0");
}

    async function loadMasterclassDate() {

        try {

            const response = await fetch(API_URL, {
                method: "GET",
                cache: "no-store",
                credentials: "same-origin"
            });

            if (!response.ok) {
                throw new Error("Unable to fetch masterclass date");
            }

            const data = await response.json();

            console.log("Thank You Masterclass Data:", data);

            if (!data.success || !data.date_time) {
                throw new Error("Invalid masterclass configuration");
            }

            if (whatsappBtn && data.whatsapp_link) {
    whatsappBtn.href = data.whatsapp_link;
    whatsappBtn.target = "_blank";
    whatsappBtn.rel = "noopener noreferrer";
}
            
            const parsedDate = new Date(data.date_time);

            if (Number.isNaN(parsedDate.getTime())) {
                throw new Error("Invalid masterclass date");
            }

            // DATE ONLY
            if (dateEl) {
                dateEl.textContent =
                    parsedDate.toLocaleDateString("en-IN", {
                        timeZone: "Asia/Kolkata",
                        day: "numeric",
                        month: "long",
                        year: "numeric"
                    });
            }

            // TIME ONLY
            if (timeEl) {
                timeEl.textContent =
                    parsedDate.toLocaleTimeString("en-IN", {
                        timeZone: "Asia/Kolkata",
                        hour: "numeric",
                        minute: "2-digit",
                        hour12: true
                    }) + " IST";
            }

            targetDate = parsedDate;

            updateCountdown();

        } catch (error) {

            console.error(
                "Thank You Page Masterclass Error:",
                error
            );

            if (dateEl) {
                dateEl.textContent = "Coming Soon";
            }

            if (timeEl) {
                timeEl.textContent = "";
            }
        }
    }

    // Immediately get latest dashboard date
    loadMasterclassDate();

    // Countdown
    setInterval(updateCountdown, 1000);

    // Refresh latest date every 60 seconds
    setInterval(loadMasterclassDate, 60000);

});
