    <script defer>
        function getTimeRemaining(endTime) {
            const total = Date.parse(endTime) - Date.parse(new Date());
            const seconds = Math.floor((total / 1000) % 60);
            const minutes = Math.floor((total / 1000 / 60) % 60);
            const hours = Math.floor((total / (1000 * 60 * 60)) % 24);
            const days = Math.floor(total / (1000 * 60 * 60 * 24));

            return {
                total,
                days,
                hours,
                minutes,
                seconds
            };
        }


        function getEndTime() {
            return new Date(2026, 3, 18, 23, 59, 59); // 18 April 2026
        }


        function padZero(number) {
            return number < 10 ? '0' + number : number;
        }

        function initializeClock() {
            const countdownElement = document.getElementById('countdown');
            const countdownElement2 = document.getElementById('countdown2');

            // Add null check
            if (!countdownElement && !countdownElement2) {
                console.warn('Countdown elements not found');
                return;
            }

            const endTime = getEndTime();

            function updateClock() {
                const t = getTimeRemaining(endTime);

                if (countdownElement) {
                    countdownElement.innerHTML = `
                    <p><span>${padZero(t.days)}</span>Days</p> :
                    <p><span>${padZero(t.hours)}</span>Hours</p> :
                    <p><span>${padZero(t.minutes)}</span>Minutes</p> :
                    <p><span>${padZero(t.seconds)}</span>Seconds</p>
                `;
                }

                if (countdownElement2) {
                    countdownElement2.innerHTML = `
                    <p><span>${padZero(t.days)}</span>Days</p>
                    <p><span>${padZero(t.hours)}</span>Hours</p>
                    <p><span>${padZero(t.minutes)}</span>Minutes</p>
                    <p><span>${padZero(t.seconds)}</span>Seconds</p>
                `;
                }

                if (t.total <= 0) {
                    clearInterval(timeInterval);
                    if (countdownElement) countdownElement.innerHTML = "Time's up!";
                    if (countdownElement2) countdownElement2.innerHTML = "Time's up!";
                }
            }

            updateClock();
            const timeInterval = setInterval(updateClock, 1000);
        }


        // Only use DOMContentLoaded
        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', initializeClock);
        } else {
            // DOM is already loaded
            initializeClock();
        }

