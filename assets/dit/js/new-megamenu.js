function updateBanner(menuType = "primary", id = "pn1") {
  const bannerWrapper = document.querySelector(".megamenu-banner");
  if (!bannerWrapper) return;

  const bannerImgEl = bannerWrapper.querySelector("img");

  const navArr =
    menuType === "primary"
      ? megaMegaMenuData.primaryNavigation
      : megaMegaMenuData.secondaryNavigation;

  const navItem = navArr.find((item) => item.id === id);

  // agar nav item hi nahi mila ya banner nahi hai -> hide
  if (!navItem || !navItem.banner || !navItem.banner.bannerImg) {
    bannerWrapper.style.display = "none";
    bannerImgEl.style.display = "none";

    return;
  }

  // banner hai -> dikhाओ
  bannerImgEl.style.display = "block";
  bannerWrapper.style.display = "flex"; // ya "block"
  bannerImgEl.src = navItem.banner.bannerImg;
  bannerImgEl.alt = navItem.banner.alt || "Mega Menu Banner";
}

//ADD ACTIVE CLASS TO SELECTED CARD //
function activateCardSelection() {
  const cards = document.querySelectorAll(".megamenu-content .megamenu-card");

  cards.forEach((card) => {
    card.addEventListener("click", () => {
      cards.forEach((c) => c.classList.remove("active"));
      card.classList.add("active");
    });
  });
}

// Hydrate Navigation with Events
function attachMenuEvents() {
  // PRIMARY MENU CLICKS
  document.querySelectorAll(".primary-navigation li").forEach((li) => {
    li.addEventListener("click", function () {
      const id = this.dataset.id;

      document
        .querySelectorAll(".primary-navigation li")
        .forEach((e) => e.classList.remove("activePrimary"));
      document
        .querySelectorAll(".secondary-navigation li")
        .forEach((e) => e.classList.remove("activeSecondary"));

      this.classList.add("activePrimary");

      loadCards("primary", id);
      updateBanner("primary", id);
    });
  });

  // SECONDARY MENU CLICKS
  document.querySelectorAll(".secondary-navigation li").forEach((li) => {
    li.addEventListener("click", function () {
      const id = this.dataset.id;

      document
        .querySelectorAll(".secondary-navigation li")
        .forEach((e) => e.classList.remove("activeSecondary"));
      document
        .querySelectorAll(".primary-navigation li")
        .forEach((e) => e.classList.remove("activePrimary"));

      this.classList.add("activeSecondary");

      loadCards("secondary", id);
      updateBanner("secondary", id);
    });
  });
}

//INITIALIZE EVERYTHING //
function initMegaMenu() {
  renderNavigation();

  const firstPrimary = document.querySelector(".primary-navigation li");
  if (firstPrimary) firstPrimary.classList.add("activePrimary");

  loadCards("primary", "pn1");
  updateBanner("primary", "pn1"); // yaha se pn1 ka banner ya hide
  attachMenuEvents();
}

// yha se chalu hoga sab initialization
initMegaMenu();
